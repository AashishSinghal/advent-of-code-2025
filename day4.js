function removeValidRolls(grid) {
  // Number of rows in the grid
  const rows = grid.length;

  // Number of columns in the grid
  const cols = grid[0].length;

  // All 8 possible neighbor directions (row offset, col offset)
  const directions = [
    [-1, -1],
    [-1, 0],
    [-1, 1], // top-left, top, top-right
    [0, -1],
    [0, 1], // left, right
    [1, -1],
    [1, 0],
    [1, 1], // bottom-left, bottom, bottom-right
  ];

  // ------------------------------------------------------------
  // STEP 1: Build adjacency count matrix
  // adjCount[r][c] = number of '@' neighbors around (r, c)
  // ------------------------------------------------------------

  const adjCount = Array.from({ length: rows }, () => Array(cols).fill(0));

  // Traverse every cell in the grid
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      // Only '@' cells care about adjacency
      if (grid[r][c] !== "@") continue;

      // Check all 8 neighboring directions
      for (const [dr, dc] of directions) {
        const nr = r + dr; // neighbor row
        const nc = c + dc; // neighbor column

        // Check bounds and whether neighbor is '@'
        if (
          nr >= 0 &&
          nr < rows &&
          nc >= 0 &&
          nc < cols &&
          grid[nr][nc] === "@"
        ) {
          adjCount[r][c]++; // increment adjacency count
        }
      }
    }
  }

  // ------------------------------------------------------------
  // STEP 2: Initialize queue with initially valid rolls
  // A valid roll = '@' with adjCount < 4
  // ------------------------------------------------------------

  const queue = []; // queue of cells to be removed

  // inQueue[r][c] prevents adding the same cell multiple times
  const inQueue = Array.from({ length: rows }, () => Array(cols).fill(false));

  // Scan grid once to find initially valid rolls
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      if (grid[r][c] === "@" && adjCount[r][c] < 4) {
        queue.push([r, c]); // enqueue cell
        inQueue[r][c] = true; // mark as queued
      }
    }
  }

  // ------------------------------------------------------------
  // STEP 3: Cascading removal using the queue
  // ------------------------------------------------------------

  let removedCount = 0; // total number of removed rolls

  // Process until no more valid rolls exist
  while (queue.length > 0) {
    // Take the next cell to process
    const [r, c] = queue.shift();

    // Guard: cell may already be removed by an earlier operation
    if (grid[r][c] !== "@") continue;

    // Remove the roll
    grid[r][c] = ".";
    removedCount++;

    // Removing this cell affects ONLY its neighbors
    for (const [dr, dc] of directions) {
      const nr = r + dr;
      const nc = c + dc;

      // Skip out-of-bounds neighbors
      if (nr < 0 || nr >= rows || nc < 0 || nc >= cols) continue;

      // Only '@' neighbors are affected
      if (grid[nr][nc] !== "@") continue;

      // One neighbor disappeared → decrement adjacency count
      adjCount[nr][nc]--;

      // If neighbor just became valid and isn't already queued
      if (adjCount[nr][nc] < 4 && !inQueue[nr][nc]) {
        queue.push([nr, nc]); // enqueue for removal
        inQueue[nr][nc] = true; // mark as queued
      }
    }
  }

  // ------------------------------------------------------------
  // STEP 4: Return useful results
  // ------------------------------------------------------------

  return {
    removedCount, // how many rolls were removed
    finalGrid: grid, // grid after all cascading removals
  };
}

