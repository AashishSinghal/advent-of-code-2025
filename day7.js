const a = input.split("\n").map((line) => line.split(""));

function findNumberOfSplits(a) {
  let splits = 0;
  const rows = a.length;
  const cols = a[0].length;
  const beams = new Set();
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      if (a[r][c] === "S") {
        beams.add(c);
      }
      if (a[r][c] === "." && beams.has(c)) {
        a[r][c] = "|";
      }
      if (a[r][c] === "^" && beams.has(c)) {
        splits++;
        beams.delete(c);
        beams.add(c - 1);
        beams.add(c + 1);
        a[r][c - 1] = "|";
        a[r][c + 1] = "|";
      }
    }
  }
  console.log(a.map((line) => line.join("")).join("\n"));
  return splits;
}

function findNumberOfTimelines(grid) {
  const ROWS = grid.length;
  const COLS = grid[0].length;
  let startCol = -1;

  for (let c = 0; c < COLS; c++) {
    if (grid[0][c] === "S") {
      startCol = c;
      break;
    }
  }

  const memo = new Map();

  function countTimelines(r, c) {
    // 1️⃣ Base case: exited the grid
    if (r >= ROWS || c < 0 || c >= COLS) {
      return 1n; // one completed timeline
    }

    const key = `${r},${c}`;
    if (memo.has(key)) {
      return memo.get(key);
    }

    let result;

    const cell = grid[r][c];

    // 2️⃣ Empty space → continue straight down
    if (cell === "." || cell === "S") {
      result = countTimelines(r + 1, c);
    }

    // 3️⃣ Splitter → branch timelines
    else if (cell === "^") {
      const left = countTimelines(r + 1, c - 1);
      const right = countTimelines(r + 1, c + 1);
      result = left + right;
    }

    // 4️⃣ Cache and return
    memo.set(key, result);
    return result;
  }

  const timelines = countTimelines(1, startCol);
  return timelines;
}

